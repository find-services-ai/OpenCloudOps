"""The ideas suite: fifteen real applications, none written for this framework.

`examples/ideas/` is generated by `scripts/generate_ideas_examples.py` from the
MCP servers in the sibling `mcp-idea-publisher` repository. Those services were
built independently, which is what makes them a fair test: nothing about them
was shaped to make OpenCloudOps look good.

Every example is put through the whole pipeline -- ground, name, tag, guard,
and render in all five IaC backends, in all three environments. That is the
matrix that would catch a regression in any one of them.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from opencloudops.emitters import available, get_emitter
from opencloudops.graph import load_graph, resolve, topological_order
from opencloudops.guard import evaluate
from opencloudops.integrations.ideas import (
    PLACEHOLDER_COST_CENTER,
    PLACEHOLDER_OWNER,
    DiscoveryError,
    discover,
)
from opencloudops.learner import Learner

EXAMPLES = sorted((Path(__file__).resolve().parent.parent / "examples" / "ideas").glob("*.graph.yaml"))
IDS = [p.name.removesuffix(".graph.yaml") for p in EXAMPLES]


def test_the_suite_is_not_empty():
    assert len(EXAMPLES) >= 15, "examples/ideas/ should hold one graph per MCP application"


@pytest.mark.parametrize("path", EXAMPLES, ids=IDS)
class TestEveryIdeaApplication:
    def test_the_graph_parses_and_orders(self, path, platform, catalog):
        graph = load_graph(path)
        assert topological_order(graph)

    @pytest.mark.parametrize("env", ["dev", "staging", "prod"])
    def test_it_grounds_and_passes_the_guard(self, path, platform, catalog, env):
        graph = load_graph(path)
        plan = resolve(graph, platform, catalog, env)
        report = evaluate(plan, platform)
        assert not report.blocked, (
            f"{path.name} ({env}) blocked: "
            + "; ".join(f"{f.rule_id} {f.node_id}: {f.message}" for f in report.blocks)
        )

    def test_it_renders_in_every_backend(self, path, platform, catalog):
        plan = resolve(load_graph(path), platform, catalog, "prod")
        for backend in available():
            files = get_emitter(backend).emit(plan, platform)
            assert files, f"{backend} emitted nothing for {path.name}"

    def test_the_rendered_output_passes_its_own_lessons(self, path, platform, catalog):
        plan = resolve(load_graph(path), platform, catalog, "prod")
        learner = Learner(memory_dir=None)
        for backend in available():
            hits = learner.blocking(
                learner.scan(get_emitter(backend).emit(plan, platform), plan, platform)
            )
            assert not hits, [f"{backend} {h.lesson_id} {h.artifact}:{h.line}" for h in hits]

    def test_names_fit_provider_limits(self, path, platform, catalog):
        plan = resolve(load_graph(path), platform, catalog, "prod")
        for node in plan.nodes:
            assert len(node.name) <= 63, f"{node.id} name is {len(node.name)} chars"
            assert node.name == node.name.lower()
            assert not node.name.startswith("-") and not node.name.endswith("-")

    def test_resource_names_are_unique_within_a_plan(self, path, platform, catalog):
        plan = resolve(load_graph(path), platform, catalog, "prod")
        names = [n.name for n in plan.nodes]
        assert len(names) == len(set(names)), "two resources resolved to one name"


class TestDiscovery:
    @pytest.fixture(scope="class")
    def ideas_dir(self, repo) -> Path:
        candidate = repo.parent / "mcp-idea-publisher" / "ideas"
        if not candidate.is_dir():
            pytest.skip("sibling mcp-idea-publisher checkout not present")
        return candidate

    def test_a_draft_is_refused_until_a_person_fills_it_in(
        self, ideas_dir, platform, catalog
    ):
        """Discovery deliberately does not guess owner or cost centre. The guard
        refusing the draft is the mechanism that makes that safe rather than
        merely polite."""
        app = next(p for p in sorted(ideas_dir.iterdir()) if (p / "Dockerfile").exists())
        graph, _ = discover(app)
        assert graph.metadata.owner == PLACEHOLDER_OWNER
        assert graph.metadata.cost_center == PLACEHOLDER_COST_CENTER

        plan = resolve(graph, platform, catalog, "dev")
        report = evaluate(plan, platform)
        assert report.blocked, "a draft with placeholder tags must not pass the guard"
        assert any(f.rule_id == "GOV-006" for f in report.blocks)

    def test_filling_in_the_placeholders_clears_the_block(
        self, ideas_dir, platform, catalog
    ):
        app = next(p for p in sorted(ideas_dir.iterdir()) if (p / "Dockerfile").exists())
        graph, _ = discover(app)
        graph.metadata.owner = "platform-team"
        graph.metadata.cost_center = "CC-1042"
        report = evaluate(resolve(graph, platform, catalog, "dev"), platform)
        assert not any(f.rule_id == "GOV-006" for f in report.findings)

    def test_discovery_defaults_to_the_stricter_classification(self, ideas_dir):
        app = next(p for p in sorted(ideas_dir.iterdir()) if (p / "Dockerfile").exists())
        graph, _ = discover(app)
        assert graph.metadata.data_classification.value in {"confidential", "restricted"}

    def test_evidence_explains_every_inferred_node(self, ideas_dir):
        app = next(p for p in sorted(ideas_dir.iterdir()) if (p / "Dockerfile").exists())
        _, discovery = discover(app)
        assert discovery.evidence["files_read"]
        assert "compute" in discovery.evidence

    def test_a_directory_with_nothing_readable_is_refused(self, tmp_path):
        (tmp_path / "empty").mkdir()
        with pytest.raises(DiscoveryError):
            discover(tmp_path / "empty")

    def test_examples_are_up_to_date(self, ideas_dir, repo):
        """A drifted example is an example that stopped testing anything."""
        import subprocess
        import sys

        result = subprocess.run(
            [sys.executable, str(repo / "scripts" / "generate_ideas_examples.py"),
             str(ideas_dir), "--check"],
            capture_output=True, text=True, cwd=repo,
        )
        assert result.returncode == 0, result.stderr
