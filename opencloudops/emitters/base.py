"""Emitter base class and registry."""

from __future__ import annotations

from abc import ABC, abstractmethod

from opencloudops.spec import NodeType, PlatformContract, ResolvedNode, ResolvedPlan

EMITTERS: dict[str, type["Emitter"]] = {}


class EmitterError(Exception):
    """Raised when a plan contains something this backend cannot render."""


class Emitter(ABC):
    """Renders a resolved plan into files.

    Subclasses register themselves by defining ``id``. ``emit`` returns a
    mapping of relative path to file content -- nothing is written to disk
    here, so a caller can diff, review, or discard a plan without side effects.
    """

    id: str = ""
    language: str = ""
    description: str = ""
    #: Node types this backend does not render. Declared, not silently skipped:
    #: ``emit`` writes an UNSUPPORTED.md naming what was left out and why.
    unsupported: tuple[NodeType, ...] = ()

    def __init_subclass__(cls, **kwargs: object) -> None:
        super().__init_subclass__(**kwargs)
        if cls.id:
            EMITTERS[cls.id] = cls

    @abstractmethod
    def emit(self, plan: ResolvedPlan, platform: PlatformContract) -> dict[str, str]:
        """Render the plan. Keys are paths relative to the output directory."""

    # -- helpers shared by every backend --------------------------------

    def supported_nodes(self, plan: ResolvedPlan) -> list[ResolvedNode]:
        return [n for n in plan.nodes if n.type not in self.unsupported]

    def skipped_nodes(self, plan: ResolvedPlan) -> list[ResolvedNode]:
        return [n for n in plan.nodes if n.type in self.unsupported]

    def skip_note(self, plan: ResolvedPlan) -> dict[str, str]:
        """An explicit record of what this backend did not render.

        Silence here would be the dangerous option: a reviewer reading only
        the emitted files would believe the whole plan was covered.
        """
        skipped = self.skipped_nodes(plan)
        if not skipped:
            return {}
        lines = [
            f"# Not rendered by the {self.language} backend",
            "",
            f"Plan `{plan.graph_name}` ({plan.environment}) contains "
            f"{len(skipped)} node(s) this backend cannot express.",
            "",
            "| node | type | why |",
            "|---|---|---|",
        ]
        for n in skipped:
            lines.append(
                f"| `{n.id}` | `{n.type.value}` | "
                f"outside the {self.language} resource model -- provision it with another backend |"
            )
        lines += [
            "",
            "These nodes are still part of the plan and still passed the guard.",
            "Render them with a backend that supports them (`occ iac --language terraform`),",
            "or remove them from the graph if they are genuinely not wanted.",
        ]
        return {"UNSUPPORTED.md": "\n".join(lines) + "\n"}

    def header(self, plan: ResolvedPlan, comment: str = "#") -> str:
        """Provenance banner. Deliberately terse -- long comment art is a
        lesson the learner actively flags (see `decorative-comments`)."""
        return "\n".join(
            [
                f"{comment} Generated by OpenCloudOps from graph '{plan.graph_name}'.",
                f"{comment} Environment: {plan.environment} ({plan.region}). Do not edit by hand:",
                f"{comment} re-run `occ iac {plan.graph_name} --env {plan.environment}` instead.",
                "",
            ]
        )


def get_emitter(name: str) -> Emitter:
    try:
        return EMITTERS[name]()
    except KeyError:
        raise EmitterError(
            f"no IaC backend named {name!r}. Available: {', '.join(sorted(EMITTERS))}"
        ) from None


def available() -> list[str]:
    return sorted(EMITTERS)
