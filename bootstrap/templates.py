"""Scaffolded document bodies.

Plain Python format strings rather than a template engine: the bootstrap
has exactly two runtime dependencies (stdlib and PyYAML), and a Jinja
dependency to interpolate six values is cost without return. Each function
takes the config and returns one file's text.
"""

from __future__ import annotations

from bootstrap.config import PlatformConfig


def aidlc_instructions(config: PlatformConfig) -> str:
    gated = [e.name for e in config.environments if not e.autonomous]
    return f"""# AIDLC -- the AI Development Life Cycle for {config.name}

The software development life cycle assumes a human writes each change and
another human reviews it. Neither assumption holds when an agent proposes
most of the diff. AIDLC is the loop that replaces them.

## The loop

```
INTENT  ->  CONTEXT  ->  PROPOSE  ->  GATE  ->  ACT  ->  OBSERVE  ->  LEARN
   ^                                                                    |
   +--------------------------------------------------------------------+
```

| Stage | Who | What must be true to leave it |
|---|---|---|
| **Intent** | Human | The goal is written down and links to a ticket. An agent that infers intent from a one-line prompt is guessing, and the guess is invisible. |
| **Context** | Agent | The agent has loaded the platform config, the relevant knowledge, and -- for a data question -- a governed catalog. Context loaded is stated, not assumed. |
| **Propose** | Agent | A diff or a plan exists, with a rationale per step. Nothing is applied yet. |
| **Gate** | Machine + human | Validation passes. {"For " + ", ".join(gated) + ", a human approves explicitly." if gated else "All environments are autonomous at their declared tier."} |
| **Act** | Agent | The change is applied to exactly one named environment. |
| **Observe** | Agent | Health is checked against a stated window, not eyeballed. |
| **Learn** | Both | The outcome updates the knowledge base or a guardrail. An incident that changes nothing will recur. |

## The three failures this exists to prevent

**Silent scope drift.** The agent was asked about dev and touched staging.
Prevented at Gate by env-leak detection, and structurally by risk tiers in
`platform.yml`: a HIGH-tier environment cannot be marked autonomous.

**Confident fabrication.** The agent explains a cost rise it never
measured. Prevented by making data access governed and cited -- see
`.github/skills/_research/mesh-research/SKILL.md`. A claim with no evidence
digest is deleted, not hedged.

**Unbounded retry.** The agent loops on a failure, spending tokens and
changing nothing. Prevented by `max_error_chain` and per-node retry
budgets in `agent-graph.yml`.

## How this differs from "just use an agent"

Every stage above has a refusal path. An AIDLC loop where the agent can
never say "I could not establish that" is not a loop, it is a pipeline with
optimism in it. The gates are the product.

## Grading your own loop

1. Can you name the environment every change touched, from the transcript alone?
2. Can you re-derive every factual claim the agent made, from artefacts it left behind?
3. When the agent was blocked, did it stop and say so, or did it improvise?
4. Did anything the agent learned survive the session?

Three yeses and a fourth is a working loop. Two is a demo.
"""


def guardrails_instructions(config: PlatformConfig) -> str:
    rows = "\n".join(
        f"| `{e.name}` | `{e.branch}` | `{e.prefix}` | {e.risk_tier} | "
        f"{'agent acts' if e.autonomous else 'human approves first'} |"
        for e in config.environments
    )
    return f"""# Guardrails -- {config.name}

Generated from `.github/config/platform.yml`. Edit that file, re-run the
bootstrap; do not edit this file by hand, or it will disagree with the
graph that enforces it.

## Environments

| Environment | Branch | Prefix | Risk tier | Agent autonomy |
|---|---|---|---|---|
{rows}

Promotion path: {" -> ".join(config.promotion_path)}. Skipping a step is a
human decision, never an agent's.

## Non-negotiable

1. **One environment per change.** A diff that names two environments is
   rejected by `change-validator`, not merged and explained.
2. **No cross-environment identifiers.** An account id, endpoint, or ARN
   belonging to another environment in a diff is a leak, whatever the
   comment next to it says.
3. **Validation is not optional.** No node reaches apply without
   `change-validator` passing. There is no fast path, including for a
   one-line change.
4. **Never disable a test or a check to get green.** If a check is wrong,
   fix the check as its own change with its own review.
5. **Data claims are cited.** Anything asserted about cost, incidents, or
   deploys carries an evidence digest from a sandboxed read, or it does not
   get asserted.
6. **The research sandbox is not kernel isolation.** It bounds reach and
   spend and leaves a ledger. It does not contain untrusted code. Never
   describe it as a VM or a container.

## Escalate rather than improvise when

- The failure recurs after one retry with the same error.
- The fix would touch an environment the request did not name.
- The fix requires credentials or a permission the agent does not have.
- The data needed to decide is not in the catalog.
"""


def cost_investigation_skill(config: PlatformConfig) -> str:
    d = config.research_sandbox_defaults
    return f"""---
name: cost-investigation
description: >
  Investigate a cloud cost change across the data mesh -- warehouse cost
  tables, deploy events, incidents, and the BI snapshot the business
  actually saw. Use when asked why spend moved, not to produce a routine
  cost report.
---

# cost-investigation

## Why this is a skill and not a query

"Why did spend go up" is never answered by the cost table alone. The cost
table says *what*. The lake says what was deployed and what broke. The BI
snapshot says what the business was told. A cost rise that coincides with a
rollback storm is a different problem from one that coincides with a new
region, and the cost table cannot tell them apart.

## Procedure

1. **Scope the sandbox.** Narrowest plane set that could answer it.

   ```
   sandbox_create(
     purpose="cost investigation: <the actual question>",
     ttl_seconds={d['ttl_seconds']}, max_queries={d['max_queries']}, max_rows={d['max_rows']},
     allowed_planes=["warehouse", "lake", "bi"],
   )
   ```

2. **Orient before reading.** `catalog_search("cost weekly service")` then
   `catalog_describe` on the top hits. Reading a table to find out what is
   in it is the most expensive way to ask a cheap question.

3. **Establish the shape.** Which service, which environment, which weeks.
   One `query_product` with an explicit `select` and a `where`.

4. **Correlate across planes.** `unified_query` joining incidents or deploy
   events to service ownership on `service`. This is the step the cost
   table cannot do alone.

5. **Check what the business saw.** Read the BI dashboard rows. If your
   number disagrees with the published one, that disagreement *is* a
   finding -- report it, do not quietly prefer your own.

6. **Report with citations.** `research_report`. Every claim carries an
   evidence digest.

## Refusals

- `classification` -> narrow `select`. Owner emails are PII; team and tier
  usually answer the question without them.
- `budget` -> add a `where` before raising `max_rows`. A filter is cheaper
  than a bigger budget and produces a better answer.
- A plane is unreachable -> say which conclusions are therefore unsupported.

## Done means

A named mechanism, a cited number, and an explicit list of what you could
not check. "Costs rose across the board" with no mechanism is not done.
"""


def incident_triage_skill(config: PlatformConfig) -> str:
    return f"""---
name: incident-triage
description: >
  Triage a {config.application} incident: establish blast radius, correlate
  with deploys, and produce a cited timeline. Use for an active or recent
  incident, not for routine health checks.
---

# incident-triage

## Order of operations

1. **Blast radius first, cause second.** `catalog_lineage(product_id=...,
   direction="down")` tells you which dashboards and datasets are affected
   before you know why. People asking "is my report wrong" need an answer
   sooner than people asking "what broke".

2. **Correlate deploys.** Read `deploy_events` filtered to the service and
   window. A `rolled_back` or `failed` outcome immediately before the
   incident is a lead, not a conclusion.

3. **Read the incident record.** Root cause, detection time, restore time.

4. **Name the mechanism.** "Flake", "transient", and "intermittent" are not
   root causes. If you cannot name the mechanism, say that you could not,
   and say what you would need to.

## What not to do

- Do not propose a fix to a source system. This agent reads and describes.
  Name what would have to do the write, and who owns it.
- Do not extrapolate from one incident to a trend. Two data points and a
  slope is not a trend, it is a line.
- Do not omit the plane you could not read. An incident report missing the
  BI plane is a report with a hole in it, and the hole belongs in the
  limits section.

## Output

A timeline with a cited row behind each entry, a named blast radius from
lineage, and a limits section. If the limits section is empty, you have not
finished looking.
"""


def mesh_research_skill(config: PlatformConfig) -> str:
    planes = sorted({m.plane for m in config.mesh}) or ["(none declared)"]
    return f"""---
name: mesh-research
description: >
  Governed cross-plane research through the sandbox-research MCP server.
  Use for any question that spans data domains. Do not use for a
  single-source query a person can run directly.
---

# mesh-research

Planes available on this platform: {", ".join(planes)}.
Server: `sandbox-research` (find-services-ai/mcp-idea-publisher,
`ideas/sandbox-research`). 17 tools.

## The loop

```
sandbox_create -> catalog_search/describe -> research_plan
               -> research_run -> research_report -> sandbox_destroy
```

## Four rules that are not style preferences

**Narrowest scope that answers the question.** Not the widest that might be
useful later. A sandbox is cheap to create and its scope is the only thing
standing between a research question and every row in the mesh.

**A refusal is information.** `reason: "classification"` means pass
`select` with permitted columns. It does not mean create a sandbox with PII
clearance -- only a person decides a question is worth reading PII for.

**Every claim cites evidence.** `research_report` returns findings with
evidence ids and digests. Do not add prose that outruns them. An uncited
claim is deleted, not softened.

**Gaps are reported.** `research_plan` names the planes it could not cover.
Carry that into the summary. A report with no limits section is not a
cleaner report, it is a less honest one.

## Honest description of the boundary

The sandbox is a policy, scope and spend envelope with an audit ledger: a
TTL, a query and row budget, a plane/domain scope, a classification
clearance, and a default-deny network policy, all checked before a backend
is touched. It is **not** kernel isolation -- no VM, no container, no
seccomp. If someone asks whether untrusted code is safe inside it, the
answer is no, not on this alone.

## Cost

- `catalog_describe` before `query_product`, always.
- Explicit `select`, always. Reading every column to look at two is how a
  PII column reaches a transcript.
- A `where` before a bigger `max_rows`.
- If the question needs tens of millions of rows, say so. It belongs in the
  warehouse, not in a research sandbox.
"""


def claude_md(config: PlatformConfig) -> str:
    gated = [e.name for e in config.environments if not e.autonomous]
    planes = ", ".join(sorted({m.plane for m in config.mesh}))
    mesh_line = (
        "- Data questions go through the `sandbox-research` MCP server. "
        f"Planes: {planes}."
        if config.mesh
        else "- No data mesh is declared. Do not assert facts about cost or incidents."
    )
    return f"""# CLAUDE.md -- {config.name}

Generated by the OpenCloudOps bootstrap from `.github/config/platform.yml`.

## What this repo is

A {config.cloud} platform managed with {config.iac_tool} on {config.compute},
operated through the agent graph in `agent-graph.yml`.

## Before you change anything

1. Read `.github/config/platform.yml`. It is the single source of truth for
   environments, risk tiers, and the data mesh.
2. Name the environment you are acting on, out loud, before acting.
3. {"Changes to " + ", ".join(gated) + " require explicit human approval." if gated else "All environments are autonomous at their declared tier."}

## Hard rules

- One environment per change. Never two.
- No cross-environment identifiers in a diff.
- `change-validator` passes before any apply. No exceptions, including
  one-line changes.
- Never disable a test or a check to get to green.
{mesh_line}
- Every factual claim about cost, incidents, or deploys carries an evidence
  digest. No digest, no claim.

## Where things are

| Path | What |
|---|---|
| `.github/config/platform.yml` | Environments, risk tiers, mesh planes |
| `agent-graph.yml` | Nodes, edges, gates, failure policy |
| `.github/instructions/aidlc.md` | The development loop and its gates |
| `.github/instructions/guardrails.md` | What the agent may and may not do |
| `.github/skills/` | Procedures: cost investigation, incident triage, mesh research |
| `mesh.yaml` | Connector manifest for the sandbox-research server |

## When you are blocked

Stop and say so. State what you established, what you could not, and what
you would need. An agent that improvises past a blocker produces work that
has to be unpicked, which costs more than the pause.
"""


def agents_md(config: PlatformConfig) -> str:
    """Agent-agnostic equivalent of CLAUDE.md."""
    return claude_md(config).replace(
        f"# CLAUDE.md -- {config.name}", f"# AGENTS.md -- {config.name}"
    ).replace(
        "Generated by the OpenCloudOps bootstrap",
        "Agent-agnostic instructions. Generated by the OpenCloudOps bootstrap",
    )
